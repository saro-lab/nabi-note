// "마크다운 같은가" — 가벼운 스니핑이다. 느슨해도 된다: 오탐은 붙여넣기 판에서 사람이
// 거르고(맨 글자 후보가 늘 옆에 선다), 놓치면 md 후보가 안 뜰 뿐 글은 그대로 붙는다.
// 신호 하나면 참이다.
const SIGNALS: readonly RegExp[] = [
  /^ {0,3}#{1,6}[ \t]/m, // 제목
  /^ {0,3}>[ \t]/m, // 인용
  /^ {0,3}[-*+][ \t]/m, // 글머리·체크 목록
  /^ {0,3}\d{1,9}[.)][ \t]/m, // 번호 목록
  /^ {0,3}(?:```|~~~)/m, // 코드 울타리
  /^ {0,3}(?:-{3,}|\*{3,}|_{3,})[ \t]*$/m, // 구분선
  /^ {0,3}\|.*\n {0,3}\|?[ \t]*:?-+/m, // 표 + 구분선
  /!\[[^\]\n]*\]\([^()\s]+\)/, // 그림
  /\[[^\]\n]+\]\([^()\s]+\)/, // 링크
  /\*\*[^*\n]+\*\*/, // 굵게
  /~~[^~\n]+~~/, // 취소선
];

export function smellsMarkdown(text: string): boolean {
  return SIGNALS.some((signal) => signal.test(text));
}
